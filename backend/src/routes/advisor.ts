import express, { Request, Response } from "express";
import { computeStatsSummary } from "../services/statsEngine";
import { explainSpendingStats } from "../services/geminiService";
import { parseMonth } from "../middleware/validation";

const router = express.Router();

/** Resolves ?month / body.month to a year+month, defaulting to the current UTC month. */
function resolveMonth(value: unknown): { year: number; month: number } | null {
    if (value === undefined || value === null || value === "") {
        const now = new Date();
        return { year: now.getUTCFullYear(), month: now.getUTCMonth() + 1 };
    }
    return parseMonth(String(value));
}

/**
 * GET /api/stats/summary?month=YYYY-MM
 * Returns pre-computed spending statistics using pure MongoDB aggregations.
 */
router.get("/summary", async (req: Request, res: Response) => {
    try {
        const period = resolveMonth(req.query.month);
        if (!period) {
            return res.status(400).json({ error: "Invalid month format. Expected YYYY-MM" });
        }

        const summary = await computeStatsSummary(req.userId!, period.year, period.month);
        res.json(summary);
    } catch (error: any) {
        res.status(500).json({ error: error.message || "Failed to compute stats summary" });
    }
});

/**
 * POST /api/stats/explain  { month?: "YYYY-MM" }
 * Returns plain-English suggestions generated by Gemini.
 * The statistics are always computed on the server from the user's own data;
 * a statsSummary sent by the client is ignored.
 */
router.post("/explain", async (req: Request, res: Response) => {
    try {
        const period = resolveMonth(req.body?.month);
        if (!period) {
            return res.status(400).json({ error: "Invalid month format. Expected YYYY-MM" });
        }

        const summaryPayload = await computeStatsSummary(req.userId!, period.year, period.month);
        const advisorResult = await explainSpendingStats(summaryPayload);

        res.json({
            statsSummary: summaryPayload,
            advisorExplanation: advisorResult
        });
    } catch (error: any) {
        res.status(500).json({ error: error.message || "Failed to generate spending advice" });
    }
});

export default router;
